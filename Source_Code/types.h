
/*******************************************
File: types.h
Controller: LPC2148 (ARM7)

Purpose:
Define shorthand names (aliases) for standard
C data types to simplify variable declarations
throughout the project.
********************************************/

typedef unsigned int u32;          // Alias for unsigned integer
typedef const char cs8;             // Alias for constant character
typedef char s8;                    // Alias for signed character type
typedef int s32;                    // Alias for signed integer
typedef unsigned char u8;           // Alias for unsigned character
typedef float f32;                  // Alias for floating-point type
typedef short int s16;              // Alias for short integer
typedef unsigned short int u16;     // Alias for unsigned short integer
typedef double f64;                 // Alias for double-precision floating-point type
